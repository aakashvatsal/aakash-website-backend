import { Type } from 'class-transformer';
import {
  IsArray,
  IsDateString,
  IsEnum,
  IsNumber,
  IsOptional,
  IsString,
  IsUrl,
  Max,
  Min,
  ValidateNested,
} from 'class-validator';

import {
  LibraryItemStatus,
  LibraryItemType,
} from '../schemas/library-item.schema';

export class SyncAppleBookItemDto {
  @IsString()
  externalId: string;

  @IsOptional()
  @IsString()
  appleBooksId?: string;

  @IsString()
  title: string;

  @IsOptional()
  @IsString()
  subtitle?: string;

  @IsOptional()
  @IsEnum(LibraryItemType)
  type?: LibraryItemType;

  @IsOptional()
  @IsEnum(LibraryItemStatus)
  status?: LibraryItemStatus;

  @IsOptional()
  @IsString()
  author?: string;

  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  authors?: string[];

  @IsOptional()
  @IsString()
  publisher?: string;

  @IsOptional()
  @IsString()
  category?: string;

  @IsOptional()
  @IsArray()
  @IsString({ each: true })
  tags?: string[];

  @IsOptional()
  @IsUrl({
    require_protocol: true,
  })
  coverImageUrl?: string;

  @IsOptional()
  @IsUrl({
    require_protocol: true,
  })
  sourceUrl?: string;

  @IsOptional()
  @IsNumber()
  @Min(0)
  @Max(100)
  progressPercentage?: number;

  @IsOptional()
  @IsNumber()
  @Min(0)
  currentPage?: number;

  @IsOptional()
  @IsNumber()
  @Min(0)
  totalPages?: number;

  @IsOptional()
  @IsDateString()
  startedAt?: string;

  @IsOptional()
  @IsDateString()
  completedAt?: string;

  @IsOptional()
  @IsDateString()
  lastReadAt?: string;

  /**
   * Hash generated by the Mac agent from the source data.
   * The backend uses it to identify unchanged records.
   */
  @IsOptional()
  @IsString()
  syncHash?: string;
}

export class SyncAppleBooksDto {
  @IsString()
  deviceId: string;

  @IsString()
  deviceName: string;

  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => SyncAppleBookItemDto)
  books: SyncAppleBookItemDto[];

  @IsOptional()
  @IsDateString()
  syncedAt?: string;
}
